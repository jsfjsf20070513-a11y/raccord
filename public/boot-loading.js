function resolveLoadingThemeKey(pathname) {
  if (pathname.startsWith('/gallery') || pathname.startsWith('/album/')) return 'gallery'
  if (pathname.startsWith('/timeline')) return 'gallery'
  if (pathname.startsWith('/announcements')) return 'gallery'
  if (pathname.startsWith('/resources')) return 'resources'
  if (pathname.startsWith('/manage') || pathname.startsWith('/login') || pathname.startsWith('/reset-password')) return 'manage'
  return 'home'
}

function getShanghaiDateKey() {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Shanghai',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date())
}

function hashString(value) {
  return Array.from(value).reduce((sum, character) => sum + character.charCodeAt(0), 0)
}

