function isValidPhrase(entry) {
  return entry && typeof entry.text === 'string' && typeof entry.note === 'string'
}

function isValidTheme(theme) {
  return (
    theme
    && typeof theme.id === 'string'
    && typeof theme.title === 'string'
    && typeof theme.badge === 'string'
    && typeof theme.kicker === 'string'
    && typeof theme.motto === 'string'
    && typeof theme.eyebrow === 'string'
    && typeof theme.ledger === 'string'
    && Array.isArray(theme.phrases)
    && theme.phrases.some(isValidPhrase)
    && theme.palette
  )
}

function getGlobalLoadingThemes() {
  if (typeof window === 'undefined') {
    return null
  }

  const themes = window.__MATH_CLASS_LOADING_THEMES__
  if (!themes || typeof themes !== 'object') {
    return null
  }

  const validEntries = Object.entries(themes).filter(([, theme]) => isValidTheme(theme))
  if (!validEntries.length) {
    return null
  }

  return Object.fromEntries(validEntries)
}

function getShanghaiDateKey() {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Shanghai',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date())
}

function hashString(value) {
  return Array.from(value).reduce((sum, character) => sum + character.charCodeAt(0), 0)
}

export function resolveLoadingThemeKey(pathname = '/') {
  if (pathname.startsWith('/gallery') || pathname.startsWith('/album/')) {
    return 'gallery'
  }

  if (pathname.startsWith('/timeline')) {
    return 'gallery'
  }

  if (pathname.startsWith('/announcements')) {
    return 'gallery'
  }

  if (pathname.startsWith('/resources')) {
    return 'resources'
  }

  if (
    pathname.startsWith('/manage')
    || pathname.startsWith('/login')
    || pathname.startsWith('/reset-password')
  ) {
    return 'manage'
  }

  return 'home'
}

export function getLoadingThemes() {
  return getGlobalLoadingThemes() || fallbackLoadingThemes
}

export function getLoadingTheme(pathname = '/') {
  const themes = getLoadingThemes()
  const key = resolveLoadingThemeKey(pathname)
  return themes[key] || themes.home || Object.values(themes)[0]
}

export function getDailyPhraseIndex(length, scope = 'default') {
  if (!length) {
    return 0
  }

  return hashString(`${scope}:${getShanghaiDateKey()}`) % length
}

export function buildLoadingSnapshot(pathname = '/', offset = 0) {
  const theme = getLoadingTheme(pathname)
  const phrases = theme.phrases.filter(isValidPhrase)
  const index = (getDailyPhraseIndex(phrases.length, theme.id) + offset) % phrases.length

  return {
    theme,
    phrases,
    index,
    entry: phrases[index] || phrases[0],
  }
}

