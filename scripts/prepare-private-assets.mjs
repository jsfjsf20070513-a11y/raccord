#!/usr/bin/env node

// Pulls real plate photos and album metadata from a sibling private repo
// at build time, so the production VPS shows the real class photos while
// the public GitHub repo never carries identifying data.
//
// Inputs (env vars):
//   MATHCLASS_PRIVATE_REPO   path to the private sibling clone, e.g.
//                            /Users/.../MathClassWebsite
//   MATHCLASS_PRIVATE_COMMIT git ref inside the private repo that holds
//                            the real albums data (default: a88bdc5)
//
// If MATHCLASS_PRIVATE_REPO is not set, this script exits cleanly without
// touching anything — `npm run build` then produces the public-safe
// placeholder version, which is the right behavior for GitHub CI.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, copyFileSync, writeFileSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OVERRIDE_PATH = join(REPO_ROOT, 'src', 'data', 'privateAlbumOverrides.js')
const UPLOADS_DEST = join(REPO_ROOT, 'public', 'uploads')

const PRIVATE_REPO = process.env.MATHCLASS_PRIVATE_REPO
const PRIVATE_COMMIT = process.env.MATHCLASS_PRIVATE_COMMIT || 'a88bdc5'

if (!PRIVATE_REPO) {
  console.log('[prepare-private-assets] MATHCLASS_PRIVATE_REPO not set — keeping public-safe placeholders.')
  process.exit(0)
}

if (!existsSync(PRIVATE_REPO)) {
  console.warn(`[prepare-private-assets] private repo not found at ${PRIVATE_REPO} — skipping.`)
  process.exit(0)
}

// 1. Read the historical siteContent.js from the private repo and slice
//    out the `albums` array (the rest of that file we don't trust here).
let historicalSiteContent
try {
  historicalSiteContent = execFileSync(
    'git',
    ['-C', PRIVATE_REPO, 'show', `${PRIVATE_COMMIT}:src/data/siteContent.js`],
    { encoding: 'utf8' },
  )
} catch (err) {
  console.error(`[prepare-private-assets] cannot read ${PRIVATE_COMMIT}:src/data/siteContent.js from ${PRIVATE_REPO}`)
  console.error(err.message)
  process.exit(1)
}

const albumsStart = historicalSiteContent.indexOf('export const albums = [')
if (albumsStart === -1) {
  console.error('[prepare-private-assets] could not locate `export const albums = [` in historical file.')
  process.exit(1)
}

let depth = 0
let cursor = historicalSiteContent.indexOf('[', albumsStart)
const arrayStart = cursor
while (cursor < historicalSiteContent.length) {
  const ch = historicalSiteContent[cursor]
  if (ch === '[') depth += 1
  else if (ch === ']') {
    depth -= 1
    if (depth === 0) break
  }
  cursor += 1
}
if (depth !== 0) {
  console.error('[prepare-private-assets] unbalanced brackets in historical albums array.')
  process.exit(1)
}
const albumsLiteral = historicalSiteContent.slice(arrayStart, cursor + 1)

// 2. Write the override file the public siteContent.js will glob-import.
const banner = [
  '// AUTO-GENERATED by scripts/prepare-private-assets.mjs at deploy time.',
  '// Do not commit. Do not edit by hand. This file is gitignored.',
  '// Source: ' + PRIVATE_REPO + ' @ ' + PRIVATE_COMMIT + ':src/data/siteContent.js',
  '',
].join('\n')
const moduleSource = `${banner}const albums = ${albumsLiteral}\n\nexport default albums\n`
writeFileSync(OVERRIDE_PATH, moduleSource, 'utf8')
console.log(`[prepare-private-assets] wrote ${OVERRIDE_PATH}`)

// 3. Copy the matching uploads/ directory from the private repo into
//    this repo's public/uploads/ so vite picks them up as static assets.
const privateUploads = join(PRIVATE_REPO, 'public', 'uploads')
if (!existsSync(privateUploads)) {
  console.warn(`[prepare-private-assets] private uploads/ not found at ${privateUploads} — albums override may reference missing files.`)
} else {
  mkdirSync(UPLOADS_DEST, { recursive: true })
  const entries = readdirSync(privateUploads, { withFileTypes: true })
  let copied = 0
  for (const entry of entries) {
    if (!entry.isFile()) continue
    copyFileSync(join(privateUploads, entry.name), join(UPLOADS_DEST, entry.name))
    copied += 1
  }
  console.log(`[prepare-private-assets] copied ${copied} file(s) from ${privateUploads} → ${UPLOADS_DEST}`)
}

console.log('[prepare-private-assets] done.')
