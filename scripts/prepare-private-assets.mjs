#!/usr/bin/env node

// Pulls real plate photos and album metadata from a sibling private repo
// at build time, so the production VPS shows the real class photos while
// the public GitHub repo never carries identifying data.
//
// Inputs (env vars):
//   MATHCLASS_PRIVATE_REPO   path to the private sibling clone, e.g.
//                            /Users/.../MathClassWebsite
//   MATHCLASS_PRIVATE_COMMIT git ref inside the private repo that holds
//                            the real albums data (default: a88bdc5)
//
// If MATHCLASS_PRIVATE_REPO is not set, this script exits cleanly without
// touching anything — `npm run build` then produces the public-safe
// placeholder version, which is the right behavior for GitHub CI.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, copyFileSync, writeFileSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OVERRIDE_PATH = join(REPO_ROOT, 'src', 'data', 'privateAlbumOverrides.js')
const UPLOADS_DEST = join(REPO_ROOT, 'public', 'uploads')

const PRIVATE_REPO = process.env.MATHCLASS_PRIVATE_REPO
const PRIVATE_COMMIT = process.env.MATHCLASS_PRIVATE_COMMIT || 'a88bdc5'

if (!PRIVATE_REPO) {
  console.log('[prepare-private-assets] MATHCLASS_PRIVATE_REPO not set — keeping public-safe placeholders.')
  process.exit(0)
}

if (!existsSync(PRIVATE_REPO)) {
  console.warn(`[prepare-private-assets] private repo not found at ${PRIVATE_REPO} — skipping.`)
  process.exit(0)
}

// 1. Read the historical siteContent.js from the private repo and slice
//    out the `albums` array (the rest of that file we don't trust here).
let historicalSiteContent
try {
  historicalSiteContent = execFileSync(
    'git',
    ['-C', PRIVATE_REPO, 'show', `${PRIVATE_COMMIT}:src/data/siteContent.js`],
    { encoding: 'utf8' },
  )
} catch (err) {
  console.error(`[prepare-private-assets] cannot read ${PRIVATE_COMMIT}:src/data/siteContent.js from ${PRIVATE_REPO}`)
  console.error(err.message)
  process.exit(1)
}

const albumsStart = historicalSiteContent.indexOf('export const albums = [')
if (albumsStart === -1) {
  console.error('[prepare-private-assets] could not locate `export const albums = [` in historical file.')
  process.exit(1)
}

let depth = 0
let cursor = historicalSiteContent.indexOf('[', albumsStart)
const arrayStart = cursor
while (cursor < historicalSiteContent.length) {
  const ch = historicalSiteContent[cursor]
  if (ch === '[') depth += 1
  else if (ch === ']') {
    depth -= 1
    if (depth === 0) break
  }
  cursor += 1
}
if (depth !== 0) {
  console.error('[prepare-private-assets] unbalanced brackets in historical albums array.')
  process.exit(1)
}
const albumsLiteral = historicalSiteContent.slice(arrayStart, cursor + 1)

// 2a. Bilingual title overlays for the production-private albums. These
//     English captions are public-safe (they describe ordinary class
//     activities that anyone arriving at the deployed site already
//     sees in the photo itself), but they keep the GitHub repo free
//     of the more detailed Chinese activity names that live only in
//     the private historical commit. Keyed by album.id so we never
//     restate the Chinese title in this public file.
const TITLE_OVERLAYS_BY_ID = {
  1: { titleEn: 'Choral assembly · 12/9 commemorative chorus' },
  2: { titleEn: 'Suzhou Museum West · museum visit' },
  3: { titleEn: 'Jiaxing field trip · class outing' },
}

// 2b. Write the override file the public siteContent.js will glob-import.
//     A small post-processing step injects the English overlays before
//     the array is emitted, so consumers can render `${titleEn} · ${title}`.
const banner = [
  '// AUTO-GENERATED by scripts/prepare-private-assets.mjs at deploy time.',
  '// Do not commit. Do not edit by hand. This file is gitignored.',
  '// Source: ' + PRIVATE_REPO + ' @ ' + PRIVATE_COMMIT + ':src/data/siteContent.js',
  '// English title overlays are merged from prepare-private-assets.mjs.',
  '',
].join('\n')
const moduleSource = [
  banner,
  'const RAW_ALBUMS = ' + albumsLiteral,
  '',
  'const TITLE_OVERLAYS_BY_ID = ' + JSON.stringify(TITLE_OVERLAYS_BY_ID, null, 2),
  '',
  'const albums = RAW_ALBUMS.map((entry) => {',
  '  const overlay = TITLE_OVERLAYS_BY_ID[entry.id]',
  '  return overlay ? { ...entry, ...overlay } : entry',
  '})',
  '',
  'export default albums',
  '',
].join('\n')
writeFileSync(OVERRIDE_PATH, moduleSource, 'utf8')
console.log(`[prepare-private-assets] wrote ${OVERRIDE_PATH}`)

// 3. Extract the matching uploads/ directory from the SAME private COMMIT
//    (not the private working tree) into this repo's public/uploads/ so
//    vite picks them up as static assets. The album metadata in step 1 is
//    read from PRIVATE_COMMIT via `git show`, so the photos must come from
//    the same commit — the private repo's working tree may be checked out
//    at a later commit that no longer tracks these historical plates,
//    which would silently ship the real album titles with broken images.
const uploadsList = execFileSync(
  'git',
  ['-C', PRIVATE_REPO, 'ls-tree', '-r', '--name-only', PRIVATE_COMMIT, '--', 'public/uploads/'],
  { encoding: 'utf8' },
)
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)

if (uploadsList.length === 0) {
  console.warn(`[prepare-private-assets] no uploads found in ${PRIVATE_COMMIT}:public/uploads/ — albums override may reference missing files.`)
} else {
  mkdirSync(UPLOADS_DEST, { recursive: true })
  let copied = 0
  for (const repoPath of uploadsList) {
    const name = repoPath.slice('public/uploads/'.length)
    if (!name) continue
    const blob = execFileSync(
      'git',
      ['-C', PRIVATE_REPO, 'show', `${PRIVATE_COMMIT}:${repoPath}`],
      { encoding: 'buffer', maxBuffer: 64 * 1024 * 1024 },
    )
    writeFileSync(join(UPLOADS_DEST, name), blob)
    copied += 1
  }
  console.log(`[prepare-private-assets] extracted ${copied} file(s) from ${PRIVATE_COMMIT}:public/uploads/ → ${UPLOADS_DEST}`)
}

console.log('[prepare-private-assets] done.')
